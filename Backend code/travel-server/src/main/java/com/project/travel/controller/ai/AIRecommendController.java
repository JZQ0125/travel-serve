    /**















     * 调用豆包 AI















     */















    private String callDoubaoAI(String systemPrompt, String userMessage) throws Exception {















        System.out.println("--- 调用豆包 AI ---");















        System.out.println("系统提示词长度: " + systemPrompt.length());















        System.out.println("用户消息长度: " + userMessage.length());















        















        try {















            JSONArray messages = new JSONArray();















            















            JSONObject systemMsg = new JSONObject();















            systemMsg.put("role", "system");















            systemMsg.put("content", systemPrompt);















            messages.add(systemMsg);















            















            JSONObject userMsg = new JSONObject();















            userMsg.put("role", "user");















            userMsg.put("content", userMessage);















            messages.add(userMsg);















            















            JSONObject requestBody = new JSONObject();















            requestBody.put("model", DOUBAO_ENDPOINT);















            requestBody.put("messages", messages);















            requestBody.put("temperature", 0.7);















            requestBody.put("max_tokens", 1500);















            















            System.out.println("请求体大小: " + requestBody.toJSONString().length() + " 字节");















            















            HttpHeaders headers = new HttpHeaders();















            headers.setContentType(MediaType.APPLICATION_JSON);















            headers.set("Authorization", "Bearer " + DOUBAO_API_KEY);















            















            // 创建带超时配置的 RestTemplate（60秒连接超时，60秒读取超时）















            SimpleClientHttpRequestFactory factory = new SimpleClientHttpRequestFactory();















            factory.setConnectTimeout(120000);  // 60秒连接超时















            factory.setReadTimeout(120000);     // 60秒读取超时















            RestTemplate restTemplate = new RestTemplate(factory);















            















            HttpEntity<String> entity = new HttpEntity<>(requestBody.toJSONString(), headers);















            















            System.out.println("发送请求到: " + DOUBAO_API_URL);















            System.out.println("正在等待豆包 API 响应（最多等待120秒）...");















            long startTime = System.currentTimeMillis();















            















            ResponseEntity<String> response = restTemplate.exchange(















                    DOUBAO_API_URL,















                    HttpMethod.POST,















                    entity,















                    String.class















            );















            















            long endTime = System.currentTimeMillis();















            System.out.println("收到响应，状态码: " + response.getStatusCode() + "，耗时: " + (endTime - startTime) + "ms");















            















            String responseBodyStr = response.getBody();















            System.out.println("响应体长度: " + (responseBodyStr != null ? responseBodyStr.length() : 0) + " 字节");















            















            if (responseBodyStr == null || responseBodyStr.isEmpty()) {















                throw new Exception("豆包 API 返回空响应");















            }















            















            JSONObject responseBody = JSONObject.parseObject(responseBodyStr);















            















            // 检查是否有错误















            if (responseBody.containsKey("error")) {















                JSONObject error = responseBody.getJSONObject("error");















                String errorMsg = error.getString("message");















                String errorType = error.getString("type");















                System.err.println("豆包 API 返回错误 [" + errorType + "]: " + errorMsg);















                throw new Exception("豆包 API 错误: " + errorMsg);















            }















            















            String content = responseBody.getJSONArray("choices")















                    .getJSONObject(0)















                    .getJSONObject("message")















                    .getString("content");















            















            System.out.println("AI 响应内容长度: " + content.length() + " 字符");















            















            return content;















            















        } catch (Exception e) {















            System.err.println("!!! 调用豆包 AI 失败 !!!");















            System.err.println("异常类型: " + e.getClass().getName());















            System.err.println("异常信息: " + e.getMessage());















            e.printStackTrace();















            throw new Exception("豆包 AI 调用失败: " + e.getMessage(), e);















        }















    }















